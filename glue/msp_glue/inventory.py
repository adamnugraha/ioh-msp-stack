"""Ansible inventory for one customer, generated from Nautobot (pushed into Semaphore)."""

from __future__ import annotations

import yaml

from . import clients
from .clients.nautobot import DEVICES_QUERY
from .common import Tenant, host_ip

# Nautobot network driver -> Ansible connection settings
ANSIBLE_BY_DRIVER = {
    "cisco_ios": {"ansible_network_os": "cisco.ios.ios", "ansible_connection": "ansible.netcommon.network_cli"},
    "cisco_xe": {"ansible_network_os": "cisco.ios.ios", "ansible_connection": "ansible.netcommon.network_cli"},
    "cisco_nxos": {"ansible_network_os": "cisco.nxos.nxos", "ansible_connection": "ansible.netcommon.network_cli"},
    "cisco_asa": {"ansible_network_os": "cisco.asa.asa", "ansible_connection": "ansible.netcommon.network_cli"},
    "arista_eos": {"ansible_network_os": "arista.eos.eos", "ansible_connection": "ansible.netcommon.network_cli"},
    "juniper_junos": {"ansible_network_os": "junipernetworks.junos.junos",
                      "ansible_connection": "ansible.netcommon.netconf"},
    "fortinet": {"ansible_network_os": "fortinet.fortios.fortios", "ansible_connection": "httpapi"},
    "mikrotik_routeros": {"ansible_network_os": "community.routeros.routeros",
                          "ansible_connection": "ansible.netcommon.network_cli"},
    # Huawei needs the community.network collection from Ansible Galaxy (not in the Ansible 13 package).
    "huawei_vrp": {"ansible_network_os": "community.network.ce", "ansible_connection": "ansible.netcommon.network_cli"},
    "aruba_aoscx": {"ansible_network_os": "arubanetworks.aoscx.aoscx", "ansible_connection": "httpapi"},
    "linux": {"ansible_connection": "ssh"},
}


def render_inventory(tenant: Tenant, devices: list[dict] | None = None) -> str:
    if devices is None:
        data = clients.nautobot().graphql(DEVICES_QUERY, {"tenant": [tenant.name]})
        devices = data["devices"]
    groups: dict[str, dict] = {}
    for device in devices:
        if (device.get("status") or {}).get("name") != "Active":
            continue
        ip = host_ip(device.get("primary_ip4")) or host_ip(device.get("primary_ip6"))
        if not ip or not device.get("name"):
            continue
        driver = ((device.get("platform") or {}).get("network_driver")) or ""
        role = ((device.get("role") or {}).get("name") or "other").replace("-", "_")
        site = ((device.get("location") or {}).get("name") or "unknown")
        host_vars = {"ansible_host": ip, "site": site, "nautobot_id": device["id"],
                     **ANSIBLE_BY_DRIVER.get(driver, {})}
        groups.setdefault(role, {"hosts": {}})["hosts"][device["name"]] = host_vars
    inventory = {"all": {"vars": {"msp_customer": tenant.code}, "children": groups}}
    return "# Generated by msp-glue from Nautobot. Do not edit in Semaphore; changes are overwritten.\n" + \
        yaml.safe_dump(inventory, sort_keys=True)
